#!/usr/bin/env python3
"""Reproduce the MX-1 offline builds and checks; never opens USB hardware.

Run from any directory using the project's Python environment. Requires the
exact original firmware and a host C compiler for the native control test.
Ghidra exports are supplied separately and are not regenerated by this script.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
from importlib.metadata import version
import json
from pathlib import Path
import shutil
import subprocess
import sys
import time

from container_tool import ORIGINAL_SHA256, extract_image

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("firmware", nargs="?", type=Path,
                        default=ROOT / "inputs/MX1_UPD.original.bin")
    parser.add_argument("--cc", default="gcc", help="Native C compiler (default: gcc)")
    args = parser.parse_args()
    source = args.firmware.resolve()
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != ORIGINAL_SHA256:
        parser.error("Input is not the exact supplied MX-1 firmware")
    compiler = shutil.which(args.cc)
    if compiler is None:
        parser.error(f"Native C compiler not found: {args.cc}")
    compiler = str(Path(compiler).resolve())

    analysis = ROOT / "analysis"
    logdir = ROOT / "build/reproduction-logs"
    analysis.mkdir(exist_ok=True)
    logdir.mkdir(parents=True, exist_ok=True)
    report = {
        "status": "running", "input_sha256": ORIGINAL_SHA256,
        "started_utc": datetime.now(timezone.utc).isoformat(),
        "python": sys.version.split()[0],
        "dependencies": {n: version(n) for n in
                         ("capstone", "unicorn", "pyelftools", "ziglang")},
        "checks": [], "hardware_access": False,
        "limits": "CPU instruction tests use explicit I/O stubs; no physical USB, flash or audio validation."
    }
    output = analysis / "reproduction.json"

    def save() -> None:
        output.write_text(json.dumps(report, indent=2) + "\n")

    def run(label: str, argv: list[str | Path]) -> None:
        print(label, flush=True)
        start = time.monotonic()
        command = [str(v) for v in argv]
        logfile = logdir / (f"{len(report['checks']) + 1:02d}-" + label + ".txt")
        with logfile.open("w") as log:
            result = subprocess.run(command, cwd=ROOT, stdout=log,
                                    stderr=subprocess.STDOUT, check=False)
        item = {"name": label, "passed": result.returncode == 0,
                "elapsed_seconds": round(time.monotonic() - start, 3),
                "log": str(logfile.relative_to(ROOT)),
                "command": command}
        report["checks"].append(item)
        save()
        if result.returncode:
            report["status"] = "failed"
            save()
            print(logfile.read_text()[-6000:], file=sys.stderr)
            raise SystemExit(f"Failed: {label}; see {logfile}")

    py = sys.executable
    save()
    extracted = ROOT / "build/extracted"
    manifest = extract_image(raw, extracted)
    (analysis / "container_manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    for name in ("boot_main", "boot_usb", "updater", "subcpu", "app_main", "app_usb"):
        shutil.copyfile(extracted / (name + ".bin"), analysis / ("container_" + name + ".bin"))
    for kind in ("main", "usb"):
        run("map-" + kind, [py, "tools/memory_map.py", "analysis/container_app_" + kind + ".bin",
                            "--output", "analysis/map-" + kind + ".json"])
    run("map-updater", [py, "tools/memory_map.py", "analysis/container_updater.bin",
                        "--output", "analysis/container_map-updater.json"])
    for script, target in (
        ("container_verify", "container_verification"),
        ("container_updater_verify", "container_updater_verification"),
        ("container_binding_verify", "container_binding_verification"),
    ):
        run(script, [py, "tools/" + script + ".py", source,
                     "--output", "analysis/" + target + ".json"])
    run("usb-descriptor-scan", [py, "tools/usb_descriptors.py", "analysis/container_app_main.bin",
                                "--output", "analysis/usb_descriptors.json"])
    run("descriptor-tests", [py, "-m", "unittest", "discover", "-s", "tests", "-v"])
    run("bridge-plan-tests", [py, "tools/linux_bridge_test.py", "-v"])
    for kind in ("host", "device"):
        builddir = "build/" + kind + "-probe"
        run("build-" + kind, [py, "tools/build_" + kind + "_probe.py", source,
                             "--output", builddir])
        verification = ("analysis/host_probe_verification.json" if kind == "host"
                        else builddir + "/arm-verification.json")
        run("arm-" + kind, [py, "tools/" + kind + "_probe_verify.py", source,
                           "--build", builddir, "--output", verification])
        name = ("MX1_UAC1_HOST_PROBE_UNTESTED.bin" if kind == "host"
                else "MX1_UAC2_DEVICE_PROBE_UNTESTED.bin")
        run("container-" + kind + "-candidate", [py, "tools/container_candidate_verify.py",
             source, builddir + "/" + name,
             "--output", "analysis/container_" + kind + "_candidate_verification.json"])
    run("original-audio-pump", [py, "sources/hardware/uac2_pump_harness.py"])
    native = ROOT / "build/device-probe/uac2_adapter_native_test"
    run("compile-native-controls", [compiler, "-std=c11", "-Wall", "-Wextra", "-Werror", "-O2",
        "-DMX1_UAC2_NATIVE_TEST", "sources/hardware/uac2_adapter.c",
        "sources/hardware/uac2_adapter_native_test.c", "-o", native])
    run("native-controls", [native])
    run("subcpu-evidence", [py, "sources/hardware/inspect_subcpu.py", source,
                            "sources/hardware", "--disassemble"])
    report["status"] = "passed"
    report["finished_utc"] = datetime.now(timezone.utc).isoformat()
    report["candidate_sha256"] = {
        kind: json.loads((ROOT / "build" / (kind + "-probe") / "build-report.json").read_text())["container_sha256"]
        for kind in ("host", "device")}
    save()
    print(f"All {len(report['checks'])} offline stages passed. Report: {output}")
    print("No hardware was accessed. These results do not establish safe flashing or working USB audio.")


if __name__ == "__main__":
    main()
